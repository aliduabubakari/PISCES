"""Export CLI help and OpenAPI from source, without starting a server or worker."""

from __future__ import annotations

import argparse
import json
import os
from pathlib import Path
import subprocess
import sys

ROOT = Path(__file__).resolve().parents[1]
COMMANDS = [
    ("pisces", "pisces.cli", []),
    *[
        (f"pisces {name}", "pisces.cli", [name])
        for name in (
            "evaluate",
            "diagnostics",
            "report-view",
            "campaign-view",
            "serve-api",
            "agent",
        )
    ],
    ("pisces-unified", "pisces.unified_evaluator", []),
    ("pisces-compare", "pisces.dag_comparator", []),
    ("pisces-diagnostics", "pisces.diagnostics", []),
    ("pisces-benchmarks", "pisces.benchmarks", []),
    *[
        (f"pisces-benchmarks {name}", "pisces.benchmarks", [name])
        for name in ("list", "build", "run")
    ],
    ("pisces-energy (low-level runner)", "pisces.energy.runtime_runner_cli", []),
]


def cli_reference() -> str:
    parts = [
        "# Generated CLI Help\n\n"
        "Generated by `python scripts/export_reference_docs.py`; do not edit.\n"
        "See [the CLI guide](../CLI_REFERENCE.md) for evidence boundaries and examples.\n"
    ]
    env = {**os.environ, "COLUMNS": "88", "NO_COLOR": "1"}
    for title, module, args in COMMANDS:
        result = subprocess.run(
            [sys.executable, "-m", module, *args, "--help"],
            cwd=ROOT,
            env=env,
            text=True,
            capture_output=True,
            check=True,
        )
        parts.append(f"\n## {title}\n\n```text\n{result.stdout.rstrip()}\n```\n")
    return "".join(parts)


def openapi_reference() -> str:
    from pisces.service.settings import Settings
    from pisces.web.app import create_app

    # A token enables the security schema; no secret or state directory is used.
    mask = os.umask(0o022)
    try:
        app = create_app(Settings(token="documentation-only-" * 3, production=True))
        document = app.openapi()
    finally:
        os.umask(mask)
    return json.dumps(document, indent=2, sort_keys=True, ensure_ascii=True) + "\n"


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--check", action="store_true", help="Fail if references are stale"
    )
    args = parser.parse_args()
    outputs = {
        ROOT / "docs/reference/cli-help.md": cli_reference(),
        ROOT / "docs/reference/openapi.json": openapi_reference(),
    }
    stale = []
    for path, content in outputs.items():
        if args.check:
            if not path.exists() or path.read_text(encoding="utf-8") != content:
                stale.append(str(path.relative_to(ROOT)))
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content, encoding="utf-8")
            print(f"Generated {path.relative_to(ROOT)}")
    if stale:
        print("Stale references: " + ", ".join(stale), file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
